import { chromium } from 'playwright';
const email = 'test-owner@example.invalid';
const password = process.env.E2E_OWNER_PASSWORD || 'CHANGE_ME_TEST_PASSWORD';
const browser = await chromium.launch({ headless: false, args: ['--no-first-run'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 950 } });
const page = await context.newPage();
page.on('console', msg => { if (msg.type() === 'error') console.log('[browser error]', msg.text()); });
await page.goto('http://localhost:3000/login', { waitUntil: 'domcontentloaded' });
await page.getByPlaceholder('Email address').fill(email);
await page.getByPlaceholder('Password').fill(password);
await page.getByRole('button', { name: /^sign\s*in/i }).click();
await page.waitForTimeout(2500);
await page.goto('http://localhost:3000/chat', { waitUntil: 'networkidle' });
await page.waitForTimeout(4000);
const text = await page.locator('body').innerText();
console.log(text.split('\n').filter(Boolean).slice(0,100).join('\n'));
await page.screenshot({ path: '/Users/zeze/.openclaw/workspace/output/qrclaw-chat-connected.png', fullPage: true });
console.log('OPENED http://localhost:3000/chat, screenshot saved. Browser left open.');
await new Promise(() => {});
